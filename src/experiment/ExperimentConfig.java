package experiment;

/**
 * Configuration for a single simulation run.
 *
 * Every field below is a default that a CLI token may override; the values as written are the
 * configuration of the reported experiments unless a run states otherwise. Arguments are
 * space-separated {@code key=value} tokens, for example
 *   seed=0 bc_recovery=0.002 n=500
 * and a bare numeric first token is also accepted as the seed.
 *
 * The hub pool (Neutral Hub Intervention section of the paper) and its silencing condition are
 * specified directly by agent id, via {@code pinOpinionIds} and {@code silentIds} below, applied
 * in {@code OpinionDynamics.evolve()}.
 */
public class ExperimentConfig {

    // ---- Run identity ----
    public int seed = 0;
    // Network-generation seed. The sentinel MIN_VALUE falls back to `seed`, so that one seed drives
    // both the network and the dynamics. See resolvedNetSeed() below.
    public int netSeed = Integer.MIN_VALUE;

    // ---- Network structure & generation ----
    // The initial follow network is generated by a directed Holme-Kim process; the other
    // generators are alternatives selectable at run time.
    public String networkType = "hk"; // dcsbm|ba|hk|ws|dms|cnn|lfr|random|read
    public int sbmK = 4;                 // DC-SBM communities
    public double sbmPin = 0.08;         // DC-SBM intra-community affinity
    public double sbmPout = 0.002;       // DC-SBM inter-community affinity
    public double sbmGamma = 2.3;        // DC-SBM Pareto in-degree exponent
    public int sbmDeg = 50;              // DC-SBM target average in-degree
    public String readPath = "results/temp/step_1000.gexf"; // network=read source .gexf
    // Holme-Kim generator parameters. The analytic degree exponent gamma = 2 + hkA/hkM targets the
    // ~2.276 follow-graph exponent reported by Kwak et al. (2010); hkPt controls the clustering
    // coefficient, whose target from the same source is ~0.072. m=15 was chosen over the
    // better-fitting m=25 on compute cost, and at m=15 the realized clustering stays about twice
    // the target: a known and accepted limitation of that choice.
    public int hkM = 15;      // out-edges per new node
    public int hkA = 4;       // initial attractiveness; gamma = 2 + hkA/hkM
    public double hkPt = 0.05; // triad-formation probability (clustering knob)
    // The parameters below were fixed by Bayesian-optimization calibration against empirical
    // targets for the follow graph and the repost graph: a heavy-tailed degree distribution
    // (Kwak et al. 2010), repost-graph sign modularity (Conover et al. 2011), and posting activity
    // by ideological bin (Buntain and Snegovaya 2025). P_u and the vocal comfort radius were
    // deliberately excluded from calibration and are swept as experimental factors instead.
    public double maxFollowCapacity = 43.8638;  // maximum number of accounts an agent may follow
    public double followProb = 0.01;            // P_f

    // ---- Feed / algorithmic exposure ----
    // alpha is the share of each feed filled from the velocity-ranked For-You stream; the remainder
    // is chronological from follows. The default 0 disables the For-You stream entirely, leaving the
    // purely chronological feed described in the paper's model section, which is the configuration
    // of every reported experiment. The feed parameters below take effect only when alpha > 0.
    public double feedAlgoShare = 0.0; // alpha: For-You share of the feed
    public int feedHopH = 4;               // h: For-You reach in hops (<=0 = global)
    // How hop distance restricts algorithmic reach. Rather than a binary cutoff at depth h, each
    // candidate is accepted with a probability P(d) decaying in the hop distance d >= 1 (see
    // AdminOptim.acceptProbability). h still caps the BFS depth, so greater distances are never
    // computed and give P = 0. "hard" is the binary cutoff (P = 1 for d <= h, else 0), kept as an
    // ablation arm; lambda = 0 degenerates every mode to no decay.
    public String feedDecayMode = "exp";     // hard|exp|inverse
    public double feedDecayLambda = 0.11;     // exp: P=exp(-lambda*(d-1)); inverse: P=1/(1+lambda*(d-1))
    public String velMode = "windowed"; // velocity scoring mode for the For-You feed (cumulative|windowed)
    // Recency dampener on the velocity score, multiplying it by exp(-age/tau). It targets the
    // self-reinforcement loop (surfaced -> more reposts -> score stays elevated -> keeps surfacing)
    // that windowed velocity scoring only partly addresses; tau <= 0 disables it.
    public double feedTimeDecayTau = 30.0;
    public int feedCapacity = 15;       // S: maximum posts delivered to a feed per access
    // P_a: the model's single global timescale knob. It gates an agent's entire per-step action
    // set, including the opinion update, so every rule in the model fires once per access rather
    // than once per step. Homogeneous across agents at construction; per-agent heterogeneity
    // remains possible through Agent.setAccessProb().
    public double accessProb = 0.1;

    // ---- Bounded-confidence opinion dynamics ----
    // P_u: per-access probability of acting on out-of-tolerance content by unfollowing and blocking
    // its author. Excluded from calibration and swept as an experimental factor, since it sets the
    // population's propensity to prune disagreeable ties and therefore governs fragmentation.
    public double pU = 0.05;
    // Rates at which bounded confidence relaxes toward its comfort-determined target, expressed as
    // the fraction of the remaining gap closed per access: bcDecRate applies when the target lies
    // below the current threshold, bcRecoveryRate when it lies above (see Agent.updateMyself). The
    // negativity-dominance asymmetry (Vallone et al. 1985; Baumeister et al. 2001) is carried
    // entirely by the ratio bcDecRate/bcRecoveryRate, which is swept rather than fixed, since
    // neither citation supplies a precise multiplier.
    public double bcRecoveryRate = 0.0001;  // gamma_bc: gap-closing rate when the target is above bc
    public double bcDecRate = 0.5;          // delta_bc: gap-closing rate when the target is below bc
    // Clamp bounds on the dynamic bounded-confidence threshold. They are sweepable so that a
    // pile-up of the bc distribution at the bounds can be tested for emergent bistability rather
    // than assumed to be an artifact of where the clamps sit. The vocal comfort radius is a
    // separate parameter and must not move with these, or the tolerance and expression thresholds
    // would be conflated (see Agent.updateMyself).
    public double bcFloor = 0.2;
    public double bcCeiling = 1.0;
    // Initial value of the bounded-confidence threshold, deliberately independent of bcCeiling.
    // Tying it to the ceiling would confound any ceiling sweep, since widening the ceiling would
    // also widen day-0 tolerance and hence the day-0 comfort probability. bcInit is also the target
    // that bcRecoveryRate reverts toward, so it must not sit at the ceiling: reverting toward the
    // ceiling would reproduce the boundary collapse the graded relaxation avoids.
    public double bcInit = 0.8;
    public boolean initOpinionClip = false; // true = clip the initial Gaussian; false = truncate by resampling
    // Initial intrinsic-opinion distribution. "gaussian" is the symmetric mean-zero generator used
    // in the reported experiments, within which initOpinionClip selects clipping or truncation.
    // "empirical" instead samples the asymmetric 7-bin survey distribution in
    // Const.EMPIRICAL_OPINION_BIN_COUNTS and ignores initOpinionClip; "uniform" draws U[-1,1].
    public String initOpinionDist = "gaussian";
    // The vocal comfort radius: the population-wide window in opinion distance from an agent's own
    // position, inside which encountered content counts as comfortable and therefore emboldens
    // expression (Agent.updateMyself). It is an absolute window, which structurally favors agents in
    // dense regions of the opinion distribution over those in sparse regions, independently of
    // network homophily. Like P_u, it is excluded from calibration and swept as an experimental
    // factor.
    public double vocalComfortRadius = 0.1;

    // ---- Repost & relay mechanism ----
    public double repostProb = 0.1; // base repost probability
    // P_r^out: repost probability for content outside the reposter's tolerance, capturing
    // occasional out-of-tolerance amplification such as quoting disagreeable content to react to it.
    public double outOfBCRepostProb = 0.01;

    // ---- Agent heterogeneity: stubbornness & capacity eviction ----
    // Stubbornness lambda. "uniform" draws it per agent from [stubMin, stubMax]; setting the two
    // equal, as here, gives the homogeneous population used in the reported experiments. "const"
    // ignores both bounds and uses Const.INITIAL_STUBBORNNESS instead.
    public String stubDist = "uniform"; // const|uniform
    public double stubMin = 0.82;
    public double stubMax = 0.82;
    public double evictBeta = -1;     // capacity eviction: <0 = evict the most distant followee; >=0 = softmax temperature
    public String initPrune = "trim"; // trim removes over-capacity followees at t=0; none starts over capacity

    // ---- Posting-probability dynamics ----
    public double initialPostProb = 0.25537;
    public double maxPostProb = 1.0;
    public double minPostProb = 0.01;
    // eta in postProb += eta * (targetPostProb - postProb): the fraction of the gap to the
    // comfort-determined target closed per access (see Agent.updateMyself).
    public double postProbRelaxRate = 0.1;

    // ---- Camp/polarization analysis (sign-based metrics only; not a dynamics parameter) ----
    // Agents with |opinion| < neutralBandHalfWidth are excluded from the two-camp partition used by
    // every sign-based analysis metric (Q_sign, Q_sign_repost, crossCuttingFraction,
    // interactionCrossCuttingFraction): they count as neither camp for those metrics. The
    // assortativity metrics are untouched, since they use each agent's continuous opinion value and
    // form no camp partition at all.
    // Conover et al. (2011)'s manual coding left roughly 5-11% of actively tweeting users
    // undecidable and excluded them from the two camps rather than force-assigning them, whereas a
    // bare sign(opinion) split has no such exclusion. The value 0.2 is not taken from that paper,
    // which partitions by network clustering and uses no numeric opinion threshold; it is the
    // boundary of the middle bin under this model's own 5-bin split of [-1,1]. Because this model
    // includes silent agents, unlike a necessarily-vocal Twitter sample, the excluded fraction is
    // expected to exceed Conover's, which is intended.
    public double neutralBandHalfWidth = 0.2;

    // ---- Scale, duration & logging ----
    public int n = 1000;
    public int steps = 40000;
    public int interactionWindow = 5000; // windowed interaction-graph snapshot interval
    public int assertInterval = 1000;    // invariant-check cadence in steps
    public boolean logRepostCascade = true;
    public boolean logGexf = true;
    // Per-post lifespan log (posts/post_lifespan.csv), written once per post when it is evicted
    // from the For-You candidate window; see AdminOptim.recordLifespan. One row per reposted post,
    // rather than one per repost event.
    public boolean logPostLifespan = true;
    // force=true deletes a pre-existing result folder instead of aborting ("never overwrite" is
    // still the default; this is an explicit opt-in escape hatch). Not part of tag() — it's a
    // run-mechanics flag, not a model parameter, so it must not affect folder identity.
    public boolean force = false;

    // Agents excluded from the For-You velocity-ranked candidate pool. Chronological reach to
    // them is untouched; see AdminOptim.computeReachable.
    public java.util.Set<Integer> algoExcludeIds = java.util.Set.of();  // excluded from the For-You velocity-ranked candidate pool only
    // ---- Pinning and silencing a hub class specified by agent id (the pathway CNA2026 actually
    // uses -- see class javadoc) ----
    // A hub pool selected from the post-equilibrium network already has an opinion-homophily-shaped,
    // camp-correlated follower base by the time it is selected. These fields instead let an
    // externally supplied id list, for example the highest-follower-count agents on the INITIAL t=0
    // network before any opinion-driven rewiring, be pinned to a target opinion and held silent.
    // That models a class of agents popular for reasons orthogonal to the topic, whose audience is
    // therefore not yet opinion-sorted.
    //
    // Pinning and silencing are separate fields, so that either can be applied without the other.
    // silentIds: ChannelMode=NONE for the whole run, so these agents post and repost nothing while
    // continuing to read their feeds and update their ties. This is the paper's silenced-hub
    // condition.
    //
    // Known caveat: the capacity-based eviction in Agent.follow() can still sever other agents'
    // follow edges INTO a silenced member, purely by opinion-distance pressure as the network sorts
    // and with no content involved, since that path is not gated on the content-reactive unfollow.
    // Silence therefore does not guarantee that a silenced agent's follower base survives intact,
    // and this has to be checked empirically per run from the periodic degree snapshots.
    public java.util.Set<Integer> silentIds = java.util.Set.of();

    // Per-agent pin target: each listed agent's intrinsic and current opinion is set to its value
    // at t=0. This is a one-time reset, not a freeze. Stubbornness is deliberately left at its
    // normal per-agent draw, not forced to 1.0, because these agents are neutral or moderate
    // through lack of engagement with the topic rather than through anchoring, so their opinion
    // should remain free to drift once engaged (matching the paper: "we confirmed these opinions
    // change negligibly during runs" is an empirical observation, not a modeling constraint).
    public java.util.Map<Integer, Double> pinOpinionIds = java.util.Map.of();

    private static java.util.Set<Integer> parseIdSet(String v) {
        if (v == null || v.isBlank()) return java.util.Set.of();
        java.util.Set<Integer> ids = new java.util.HashSet<>();
        for (String tok : v.split(",")) ids.add(Integer.parseInt(tok.trim()));
        return ids;
    }

    // Format: "id:opinion,id:opinion,..." e.g. "12:0.8,47:-0.4"
    private static java.util.Map<Integer, Double> parseIdValueMap(String v) {
        if (v == null || v.isBlank()) return java.util.Map.of();
        java.util.Map<Integer, Double> m = new java.util.HashMap<>();
        for (String tok : v.split(",")) {
            int c = tok.indexOf(':');
            m.put(Integer.parseInt(tok.substring(0, c).trim()), Double.parseDouble(tok.substring(c + 1).trim()));
        }
        return m;
    }

    public static ExperimentConfig fromArgs(String[] args) {
        ExperimentConfig c = new ExperimentConfig();
        if (args.length > 0 && !args[0].contains("=")) {
            c.seed = Integer.parseInt(args[0].trim());
        }
        for (String a : args) {
            int eq = a.indexOf('=');
            if (eq < 0) continue;
            String k = a.substring(0, eq).trim();
            String v = a.substring(eq + 1).trim();
            switch (k) {
                case "seed" -> c.seed = Integer.parseInt(v);
                case "alpha" -> c.feedAlgoShare = Double.parseDouble(v);
                case "hop" -> c.feedHopH = Integer.parseInt(v);
                case "feed_decay_mode" -> c.feedDecayMode = v.toLowerCase();
                case "feed_decay_lambda" -> c.feedDecayLambda = Double.parseDouble(v);
                case "feed_time_decay_tau" -> c.feedTimeDecayTau = Double.parseDouble(v);
                case "bc_recovery" -> c.bcRecoveryRate = Double.parseDouble(v);
                case "p_u" -> c.pU = Double.parseDouble(v);
                case "max_follow" -> c.maxFollowCapacity = Double.parseDouble(v);
                case "net_seed" -> c.netSeed = Integer.parseInt(v);
                case "out_of_bc_repost_prob" -> c.outOfBCRepostProb = Double.parseDouble(v);
                case "bc_dec" -> c.bcDecRate = Double.parseDouble(v);
                case "bc_floor" -> c.bcFloor = Double.parseDouble(v);
                case "bc_ceiling" -> c.bcCeiling = Double.parseDouble(v);
                case "bc_init" -> c.bcInit = Double.parseDouble(v);
                case "vocal_comfort_radius" -> c.vocalComfortRadius = Double.parseDouble(v);
                case "init_op" -> c.initOpinionClip = v.equalsIgnoreCase("clip");
                case "init_dist" -> c.initOpinionDist = v.toLowerCase();
                case "assert_int" -> c.assertInterval = Integer.parseInt(v);
                case "network" -> c.networkType = v.toLowerCase();
                case "sbm_k" -> c.sbmK = Integer.parseInt(v);
                case "sbm_pin" -> c.sbmPin = Double.parseDouble(v);
                case "sbm_pout" -> c.sbmPout = Double.parseDouble(v);
                case "sbm_gamma" -> c.sbmGamma = Double.parseDouble(v);
                case "sbm_deg" -> c.sbmDeg = Integer.parseInt(v);
                case "read_path" -> c.readPath = v;
                case "hk_m" -> c.hkM = Integer.parseInt(v);
                case "hk_a" -> c.hkA = Integer.parseInt(v);
                case "hk_pt" -> c.hkPt = Double.parseDouble(v);
                case "repost_prob" -> c.repostProb = Double.parseDouble(v);
                case "stub_dist" -> c.stubDist = v.toLowerCase();
                case "stub_min" -> c.stubMin = Double.parseDouble(v);
                case "stub_max" -> c.stubMax = Double.parseDouble(v);
                case "evict_beta" -> c.evictBeta = Double.parseDouble(v);
                case "init_prune" -> c.initPrune = v.toLowerCase();
                case "vel_mode" -> c.velMode = v.toLowerCase();
                case "interaction_window" -> c.interactionWindow = Integer.parseInt(v);
                case "n" -> c.n = Integer.parseInt(v);
                case "steps" -> c.steps = Integer.parseInt(v);
                case "log_repost_cascade" -> c.logRepostCascade = Boolean.parseBoolean(v);
                case "log_gexf" -> c.logGexf = Boolean.parseBoolean(v);
                case "log_post_lifespan" -> c.logPostLifespan = Boolean.parseBoolean(v);
                case "force" -> c.force = Boolean.parseBoolean(v);
                case "feed_capacity" -> c.feedCapacity = Integer.parseInt(v);
                case "follow_prob" -> c.followProb = Double.parseDouble(v);
                case "initial_pp" -> c.initialPostProb = Double.parseDouble(v);
                case "max_pp" -> c.maxPostProb = Double.parseDouble(v);
                case "min_pp" -> c.minPostProb = Double.parseDouble(v);
                case "pp_relax_eta" -> c.postProbRelaxRate = Double.parseDouble(v);
                case "neutral_band" -> c.neutralBandHalfWidth = Double.parseDouble(v);
                case "access_prob" -> c.accessProb = Double.parseDouble(v);
                case "algo_exclude_ids" -> c.algoExcludeIds = parseIdSet(v);
                case "pin_opinion_ids" -> c.pinOpinionIds = parseIdValueMap(v);
                case "silent_ids" -> c.silentIds = parseIdSet(v);
                case "results_subdir" -> c.resultsSubdir = v;
                default -> { /* ignore unknown keys */ }
            }
        }
        return c;
    }

    // A single plain instance built from the field initializers above, so that tag() has exactly
    // one thing to compare against and cannot drift from the defaults it is describing.
    private static final ExperimentConfig DEFAULTS = new ExperimentConfig();

    /** Resolved network seed; the sentinel falls back to the run seed. */
    public int resolvedNetSeed() {
        return (netSeed == Integer.MIN_VALUE) ? seed : netSeed;
    }

    // Optional grouping subfolder under results/, so that a batch of runs lands pre-sorted instead
    // of hundreds of run_<seed>_<tag> folders sitting flat. Empty by default.
    public String resultsSubdir = "";

    /** Per-run output folder. */
    public String resultFolder() {
        String prefix = resultsSubdir.isBlank() ? "" : resultsSubdir + "/";
        return "results/" + prefix + "run_" + seed + "_" + tag() + "/";
    }

    /** Compact, filesystem-safe tag identifying this configuration. */
    public String tag() {
        String t = "";
        // One rule throughout: tag a field if and only if it differs from DEFAULTS. `h` is still
        // shown only alongside `alpha` when alpha > 0, since it has no meaning once the For-You
        // feed is off.
        if (feedAlgoShare != DEFAULTS.feedAlgoShare || feedHopH != DEFAULTS.feedHopH
                || !feedDecayMode.equals(DEFAULTS.feedDecayMode) || feedDecayLambda != DEFAULTS.feedDecayLambda) {
            t += "_a-" + String.format("%.2f", feedAlgoShare);
            if (feedAlgoShare > 0.0) {
                t += "_h-" + feedHopH;
                // decay mode/lambda are meaningless once alpha=0 (For-You off), same nesting as h.
                if (!feedDecayMode.equals(DEFAULTS.feedDecayMode)) t += "_decay-" + feedDecayMode;
                if (!feedDecayMode.equals("hard") && feedDecayLambda != DEFAULTS.feedDecayLambda) {
                    t += "_lam-" + String.format("%.2f", feedDecayLambda);
                }
            }
        }
        if (feedTimeDecayTau != DEFAULTS.feedTimeDecayTau) t += "_tdtau-" + String.format("%.1f", feedTimeDecayTau);
        if (pU != DEFAULTS.pU) {
            t += "_pu-" + String.format("%.4f", pU);
        }
        if (maxFollowCapacity != DEFAULTS.maxFollowCapacity) {
            t += "_maxf-" + (int) maxFollowCapacity;
        }
        if (bcDecRate != DEFAULTS.bcDecRate) {
            t += "_bcdec-" + String.format("%.4f", bcDecRate);
        }
        if (bcRecoveryRate != DEFAULTS.bcRecoveryRate) {
            t += "_bcrecovery-" + String.format("%.4f", bcRecoveryRate);
        }
        if (bcFloor != DEFAULTS.bcFloor) {
            t += "_bcfloor-" + String.format("%.4f", bcFloor);
        }
        if (bcCeiling != DEFAULTS.bcCeiling) {
            t += "_bcceil-" + String.format("%.4f", bcCeiling);
        }
        if (bcInit != DEFAULTS.bcInit) {
            t += "_bcinit-" + String.format("%.4f", bcInit);
        }
        if (vocalComfortRadius != DEFAULTS.vocalComfortRadius) {
            t += "_vcr-" + String.format("%.4f", vocalComfortRadius);
        }
        if (outOfBCRepostProb != DEFAULTS.outOfBCRepostProb) {
            t += "_outofbcprob-" + String.format("%.3f", outOfBCRepostProb);
        }
        if (initOpinionClip) {
            t += "_initop-clip";
        }
        if (!initOpinionDist.equals(DEFAULTS.initOpinionDist)) {
            t += "_initdist-" + initOpinionDist;
        }
        if (netSeed != Integer.MIN_VALUE && netSeed != seed) {
            t += "_nseed-" + netSeed;
        }
        if (!networkType.equals(DEFAULTS.networkType)) {
            t += "_nw-" + networkType;
        }
        // Structural generator parameters are tagged whenever non-default, so that two runs at the
        // same seed differing only in, say, sbm_pout cannot collide on one folder name and have the
        // second aborted by the "never overwrite" guard.
        if (sbmK != DEFAULTS.sbmK) t += "_sbmk-" + sbmK;
        if (sbmPin != DEFAULTS.sbmPin) t += "_sbmpin-" + String.format("%.4f", sbmPin);
        if (sbmPout != DEFAULTS.sbmPout) t += "_sbmpout-" + String.format("%.4f", sbmPout);
        if (sbmGamma != DEFAULTS.sbmGamma) t += "_sbmgamma-" + String.format("%.2f", sbmGamma);
        if (sbmDeg != DEFAULTS.sbmDeg) t += "_sbmdeg-" + sbmDeg;
        if (hkM != DEFAULTS.hkM) t += "_hkm-" + hkM;
        if (hkA != DEFAULTS.hkA) t += "_hka-" + hkA;
        if (hkPt != DEFAULTS.hkPt) t += "_hkpt-" + String.format("%.2f", hkPt);
        if (repostProb != DEFAULTS.repostProb) t += "_rp-" + String.format("%.3f", repostProb);
        if (!stubDist.equals(DEFAULTS.stubDist)) t += "_stub-" + stubDist + String.format("-%.2f-%.2f", stubMin, stubMax);
        if (evictBeta != DEFAULTS.evictBeta) t += "_eb-" + String.format("%.2f", evictBeta);
        if (!initPrune.equals(DEFAULTS.initPrune)) t += "_prune-" + initPrune;
        if (!velMode.equals(DEFAULTS.velMode)) t += "_vm-" + velMode;
        if (n != DEFAULTS.n) t += "_n-" + n;
        if (steps != DEFAULTS.steps) t += "_st-" + steps;
        if (feedCapacity != DEFAULTS.feedCapacity) t += "_fc-" + feedCapacity;
        if (followProb != DEFAULTS.followProb) t += "_folp-" + String.format("%.3f", followProb);
        if (initialPostProb != DEFAULTS.initialPostProb) t += "_ipp-" + String.format("%.3f", initialPostProb);
        if (maxPostProb != DEFAULTS.maxPostProb) t += "_mxpp-" + String.format("%.3f", maxPostProb);
        if (minPostProb != DEFAULTS.minPostProb) t += "_mnpp-" + String.format("%.3f", minPostProb);
        if (postProbRelaxRate != DEFAULTS.postProbRelaxRate) t += "_ppeta-" + String.format("%.4f", postProbRelaxRate);
        if (neutralBandHalfWidth != DEFAULTS.neutralBandHalfWidth) t += "_neutband-" + String.format("%.3f", neutralBandHalfWidth);
        if (accessProb != DEFAULTS.accessProb) t += "_ap-" + String.format("%.4f", accessProb);
        return t;
    }
}
